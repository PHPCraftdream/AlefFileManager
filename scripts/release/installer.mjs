// renderControl in bundle-formats.mjs has a fixed key list without Depends, so the deb
// control is rendered here with the same validation rules and this fixed key order.
const DEB_CONTROL_KEYS = ['Package', 'Version', 'Architecture', 'Depends', 'Maintainer', 'Description', 'Installed-Size'];

function renderDebControl(fields) {
  for (const key of DEB_CONTROL_KEYS) {
    if (!(key in fields)) continue;
    const value = fields[key];
    if (typeof value !== 'string' || value === '' || /[\n\r\u0000-\u001f\u007f]/.test(value)) {
      throw new Error(`Deb control: invalid field '${key}'`);
    }
  }
  return DEB_CONTROL_KEYS.filter(key => key in fields)
    .map(key => `${key}: ${fields[key]}`)
    .join('\n') + '\n';
}

function requireDebPackageName(name) {
  if (!/^[a-z0-9][a-z0-9+.-]*$/.test(name)) {
    throw new Error(`Deb control: invalid package name: '${name}'`);
  }
  return name;
}

// Shared .deb layout: ar with debian-binary, gzipped control tar, gzipped data tar.
function buildRuntimeDeb({ control, controlScripts, data }) {
  const controlTar = writeGzip(writeTar([
    { name: './control', data: Buffer.from(control, 'utf8'), mode: 0o644 },
    ...controlScripts.map(script => ({ name: './' + script.name, data: Buffer.from(script.data, 'utf8'), mode: 0o755 })),
  ]));
  const dataTar = writeGzip(writeTar(data));
  return writeAr([
    { name: 'debian-binary', data: Buffer.from('2.0\n', 'utf8') },
    { name: 'control.tar.gz', data: controlTar },
    { name: 'data.tar.gz', data: dataTar },
  ]);
}

function buildLinux({ version, runtime, maintainer }) {
  const v = requireVersion(version);
  const bytes = requireRuntime(runtime);
  const postinst = maintainerScript(POSTINST, v);
  const prerm = maintainerScript(PRERM, v);
  const postrm = maintainerScript(POSTRM, v);
  const pkg = requireDebPackageName(`alef-runtime-${v}`);
  const commonPostinst = maintainerScript(COMMON_POSTINST, v);
  const commonControl = renderDebControl({
    Package: 'alef-runtime-common',
    Version: v,
    Architecture: 'amd64',
    Maintainer: maintainer ?? DEFAULT_MAINTAINER,
    Description: 'Shared integration files for the Alef runtime (file type and application entry).',
    'Installed-Size': String(Math.ceil((postinst.length + postrm.length + MIME_XML.length + DESKTOP_ENTRY.length) / 1024)),
  });
  const commonDeb = buildRuntimeDeb({
    control: commonControl,
    controlScripts: [{ name: 'postinst', data: commonPostinst }, { name: 'postrm', data: postrm }],
    data: [
      { name: './usr/share/mime/packages/alef.xml', data: Buffer.from(MIME_XML, 'utf8'), mode: 0o644 },
      { name: './usr/share/applications/alef-runtime.desktop', data: Buffer.from(DESKTOP_ENTRY, 'utf8'), mode: 0o644 },
    ],
  });
  const control = renderDebControl({
    Package: pkg,
    Version: v,
    Architecture: 'amd64',
    Depends: 'alef-runtime-common',
    Maintainer: maintainer ?? DEFAULT_MAINTAINER,
    Description: `Alef runtime ${v}: runs Alef web applications (.alef packages).`,
    'Installed-Size': String(Math.ceil((bytes.length + postinst.length + prerm.length) / 1024)),
  });
  // /usr/bin/alef is intentionally NOT shipped: update-alternatives owns it.
  const deb = buildRuntimeDeb({
    control,
    controlScripts: [{ name: 'postinst', data: postinst }, { name: 'prerm', data: prerm }],
    data: [
      { name: './opt/alef-runtime/' + v, type: '5', mode: 0o755 },
      { name: './opt/alef-runtime/' + v + '/alef', data: bytes, mode: 0o755 },
    ],
  });
  return [
    { path: `alef-runtime-${v}_amd64.deb`, data: deb, mode: 0o644 },
    { path: `alef-runtime-common_${v}_amd64.deb`, data: commonDeb, mode: 0o644 },
  ];
}

// renderControl/Info.plist cannot express UTI keys on their own, so osacompile builds
// the applet bundle on the runner and build-pkg.sh injects the plist entries there.
const APPLESCRIPT = [
  '-- Alef runtime double-click handler: each opened .alef file is run by the launcher.',
  'on open theFiles',
  '\trepeat with aFile in theFiles',
  '\t\tdo shell script "/usr/local/bin/alef run " & quoted form of (POSIX path of aFile)',
  '\tend repeat',
  'end open',
  '',
  'on run',
  '\t-- Launched without documents: nothing to do.',
  'end run',
  '',
].join('\n');

function renderDistributionXml(version) {
  const v = escapeXml(version);
  return `<?xml version="1.0" encoding="utf-8"?>
<installer-gui-script minSpecVersion="1">
    <title>Alef Runtime ${v}</title>
    <options customize="never" require-scripts="false"/>
    <domains enable_anywhere="false" enable_currentUserHome="false" enable_localSystem="true"/>
    <pkg-ref id="org.alef.runtime"/>
    <choices-outline>
        <line choice="org.alef.runtime"/>
    </choices-outline>
    <choice id="org.alef.runtime" visible="true" title="Alef Runtime ${v}">
        <pkg-ref id="org.alef.runtime"/>
    </choice>
    <pkg-ref id="org.alef.runtime" version="${v}" onConclusion="none">alef-runtime-${v}-core.pkg</pkg-ref>
</installer-gui-script>
`;
}

function buildPkgScript(version) {
  const v = requireVersion(version);
  return `#!/bin/sh
# Builds the real .pkg with Apple tools (run on a macOS runner).
set -e
cd "$(dirname "$0")"
# An AppleScript applet receives Finder document-open events; a shell script does not.
# osacompile needs an existing parent directory (it fails with -4960 otherwise) and a fresh target.
mkdir -p payload/Applications
rm -rf payload/Applications/Alef.app
osacompile -o "$PWD/payload/Applications/Alef.app" "$PWD/applet/applet.applescript"
plist="payload/Applications/Alef.app/Contents/Info.plist"
pb() { /usr/libexec/PlistBuddy -c "$1" "$plist"; }
# osacompile already writes some keys: replace them instead of failing on Add.
set_key() { pb "Delete :$1" 2>/dev/null || true; pb "Add :$1 $2 $3"; }
set_key CFBundleIdentifier string org.alef.runtime.stub
set_key CFBundleShortVersionString string ${v}
set_key CFBundleVersion string ${v}
pb "Delete :UTExportedTypeDeclarations" 2>/dev/null || true
pb "Add :UTExportedTypeDeclarations array"
pb "Add :UTExportedTypeDeclarations:0 dict"
pb "Add :UTExportedTypeDeclarations:0:UTTypeIdentifier string org.alef.package"
pb "Add :UTExportedTypeDeclarations:0:UTTypeDescription string Alef application package"
pb "Add :UTExportedTypeDeclarations:0:UTTypeConformsTo array"
pb "Add :UTExportedTypeDeclarations:0:UTTypeConformsTo:0 string public.data"
pb "Add :UTExportedTypeDeclarations:0:UTTypeTagSpecification dict"
pb "Add :UTExportedTypeDeclarations:0:UTTypeTagSpecification:public.filename-extension array"
pb "Add :UTExportedTypeDeclarations:0:UTTypeTagSpecification:public.filename-extension:0 string alef"
pb "Delete :CFBundleDocumentTypes" 2>/dev/null || true
pb "Add :CFBundleDocumentTypes array"
pb "Add :CFBundleDocumentTypes:0 dict"
pb "Add :CFBundleDocumentTypes:0:LSItemContentTypes array"
pb "Add :CFBundleDocumentTypes:0:LSItemContentTypes:0 string org.alef.package"
pb "Add :CFBundleDocumentTypes:0:CFBundleTypeName string Alef application package"
pb "Add :CFBundleDocumentTypes:0:CFBundleTypeRole string Viewer"
pkgbuild --root payload --scripts scripts --identifier org.alef.runtime --version ${v} --install-location / "alef-runtime-${v}-core.pkg"
productbuild --distribution Distribution.xml --package-path . "alef-runtime-${v}.pkg"
`;
}

function buildDarwin({ version, runtime }) {
  const v = requireVersion(version);
  const bytes = requireRuntime(runtime);
  return [
    { path: `payload/Library/Alef/runtime/${v}/alef`, data: bytes, mode: 0o755 },
    { path: 'applet/applet.applescript', data: Buffer.from(APPLESCRIPT, 'utf8'), mode: 0o644 },
    { path: 'scripts/preinstall', data: Buffer.from('#!/bin/sh\nmkdir -p /Library/Alef/runtime /usr/local/bin\nexit 0\n', 'utf8'), mode: 0o755 },
    { path: 'scripts/postinstall', data: Buffer.from(`#!/bin/sh\nln -sfn "/Library/Alef/runtime/${v}/alef" /usr/local/bin/alef\nexit 0\n`, 'utf8'), mode: 0o755 },
    { path: 'Distribution.xml', data: Buffer.from(renderDistributionXml(v), 'utf8'), mode: 0o644 },
    { path: 'build-pkg.sh', data: Buffer.from(buildPkgScript(v), 'utf8'), mode: 0o755 },
  ];
}

const BUILDERS = {
  'win32-x64': buildWin32,
  'linux-x64': buildLinux,
  'darwin-arm64': buildDarwin,
  'darwin-x64': buildDarwin,
};

export function buildRuntimeInstaller({ platform, version, runtime, maintainer }) {
  if (!INSTALLER_PLATFORMS.includes(platform)) {
    throw new Error(`Installer: unknown platform: '${platform}'`);
  }
  // Validation-first: all rejections happen before any content is produced.
  requireVersion(version);
  requireRuntime(runtime);
  const files = Object.freeze(BUILDERS[platform]({ version, runtime, maintainer })
    .map(file => Object.freeze({ ...file })));
  return Object.freeze({ platform, version, files });
}

function runCli(argv) {
  const [platform, version, runtimeBinary, outDir] = argv;
  if (!platform || !version || !runtimeBinary || !outDir) {
    throw new Error('usage: node scripts/release/installer.mjs <platform> <version> <runtime-binary> <out-dir>');
  }
  const installer = buildRuntimeInstaller({ platform, version, runtime: readFileSync(runtimeBinary) });
  for (const file of installer.files) {
    const target = path.join(outDir, ...file.path.split('/'));
    mkdirSync(path.dirname(target), { recursive: true });
    writeFileSync(target, file.data, { mode: file.mode });
    console.log(`${file.path} (${file.data.length} bytes)`);
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  try {
    runCli(process.argv.slice(2));
  } catch (error) {
    console.error('installer: ' + (error?.message ?? error));
    process.exit(1);
  }
}
