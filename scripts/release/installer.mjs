// Deterministic, dependency-free installer generators for the Alef runtime binary:
// NSIS staging tree (win32), .deb with maintainer scripts (linux), pkg staging
// tree (darwin). Pure functions of the arguments; no fs access in the builders.
//   node scripts/release/installer.mjs <platform> <version> <runtime-binary> <out-dir>

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import {
  writeAr, writeGzip, writeTar,
  escapeXml, escapeDesktopValue, quoteDesktopExec,
} from '../../packages/tools/src/workflow/bundle-formats.mjs';

export const INSTALLER_PLATFORMS = Object.freeze(['win32-x64', 'linux-x64', 'darwin-arm64', 'darwin-x64']);

const STRICT_VERSION = /^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)$/;
const DEFAULT_MAINTAINER = 'Alef Runtime <runtime@alef.invalid>';

export function isStrictRuntimeVersion(value) {
  if (typeof value !== 'string') return false;
  // `$` alone also matches before a final newline; pin the match to the whole string.
  const match = STRICT_VERSION.exec(value);
  return match !== null && match[0] === value;
}

function requireVersion(version) {
  if (!isStrictRuntimeVersion(version)) {
    throw new Error(`Installer: version must be strict MAJOR.MINOR.PATCH semver: '${version}'`);
  }
  return version;
}

function requireRuntime(runtime) {
  if (!Buffer.isBuffer(runtime) || runtime.length === 0) {
    throw new Error('Installer: runtime must be a nonempty Buffer');
  }
  return runtime;
}

// Strictly monotonic in semver order so update-alternatives prefers the newest
// deb-installed version. Components must fit the fixed 4/4-digit slots.
export function alternativesPriority(version) {
  const parts = requireVersion(version).split('.').map(Number);
  if (parts.some(n => n > 9999)) {
    throw new Error(`Installer: version components must be <= 9999: '${version}'`);
  }
  return parts[0] * 100000000 + parts[1] * 10000 + parts[2];
}

// The runtime store root on Windows is dirs::data_local_dir()/alef/runtimes/<v>/alef.exe
// (backend/crates/alef/src/runtimes/store.rs + consent::runtime_home), i.e.
// %LOCALAPPDATA%\alef\runtimes\<v>\alef.exe: the installer installs exactly there so
// installed versions are immediately visible to `alef runtime list`/select/prune.
// The version is charset-safe by construction (strict semver regex), so it is placed
// literally in the NSIS text; only NSIS variables ($LOCALAPPDATA etc.) appear verbatim.
function renderNsisScript(version) {
  const v = requireVersion(version);
  const arp = 'Software\\Microsoft\\Windows\\CurrentVersion\\Uninstall\\AlefRuntime-' + v;
  return `; Generated by scripts/release/installer.mjs. Compile: makensis alef-runtime-${v}-setup.nsi
Unicode true
RequestExecutionLevel user
Name "Alef Runtime ${v}"
OutFile "alef-runtime-${v}-setup.exe"
InstallDir "$LOCALAPPDATA\\alef\\runtimes\\${v}"

!include "StrFunc.nsh"
\${StrStr}
\${UnStrRep}

Section "Install"
  SetOutPath "$INSTDIR"
  File /oname=alef.exe bin\\alef.exe
  CreateDirectory "$LOCALAPPDATA\\alef\\bin"
  SetOutPath "$LOCALAPPDATA\\alef\\bin"
  File /oname=alef.cmd bin\\alef.cmd
  SetOutPath "$INSTDIR"
  ; User PATH (HKCU), only once.
  ReadRegStr $R0 HKCU "Environment" "Path"
  StrCpy $R1 "$LOCALAPPDATA\\alef\\bin"
  \${StrStr} $R2 "$R0" "$R1"
  StrCmp $R2 "" 0 path_done
  StrCmp $R0 "" 0 path_append
  WriteRegExpandStr HKCU "Environment" "Path" "$R1"
  Goto path_done
path_append:
  WriteRegExpandStr HKCU "Environment" "Path" "$R0;$R1"
path_done:
  ; .alef file association (per-user), version-independent command.
  WriteRegStr HKCU "Software\\Classes\\.alef" "" "Alef.Package"
  WriteRegStr HKCU "Software\\Classes\\.alef" "Content Type" "application/x-alef-package"
  WriteRegStr HKCU "Software\\Classes\\Alef.Package" "" "Alef application package"
  WriteRegStr HKCU "Software\\Classes\\Alef.Package\\DefaultIcon" "" "$INSTDIR\\alef.exe"
  WriteRegStr HKCU "Software\\Classes\\Alef.Package\\shell\\open\\command" "" "$\\"$LOCALAPPDATA\\alef\\bin\\alef.cmd$\\" run $\\"%1$\\""
  ; Per-version Add/Remove Programs entry.
  WriteRegStr HKCU "${arp}" "DisplayName" "Alef Runtime ${v}"
  WriteRegStr HKCU "${arp}" "DisplayVersion" "${v}"
  WriteRegStr HKCU "${arp}" "Publisher" "Alef"
  WriteRegStr HKCU "${arp}" "DisplayIcon" "$INSTDIR\\alef.exe"
  WriteRegStr HKCU "${arp}" "UninstallString" "$\\"$INSTDIR\\uninstall.exe$\\""
  WriteRegDWORD HKCU "${arp}" "NoModify" 1
  WriteRegDWORD HKCU "${arp}" "NoRepair" 1
  WriteUninstaller "uninstall.exe"
  ; Broadcast so new processes pick up the changed PATH.
  SendMessage 0xFFFF 0x001A 0 "STR:Environment"
SectionEnd

Section "un.Uninstall"
  Delete "$INSTDIR\\alef.exe"
  Delete "$INSTDIR\\uninstall.exe"
  RMDir "$INSTDIR"
  RMDir "$LOCALAPPDATA\\alef\\runtimes"
  DeleteRegKey HKCU "${arp}"
  ; Only when this was the last installed version: shim, PATH entry, association.
  ; Any remaining version directory (besides . and ..) means "not the last".
  StrCpy $R4 "last"
  FindFirst $R0 $R1 "$LOCALAPPDATA\\alef\\runtimes\\*.*"
find_loop:
  StrCmp $R1 "" find_done 0
  StrCmp $R1 "." find_next 0
  StrCmp $R1 ".." find_next 0
  StrCpy $R4 "notlast"
  Goto find_done
find_next:
  FindNext $R0 $R1
  Goto find_loop
find_done:
  FindClose $R0
  StrCmp $R4 "notlast" un_done 0
  RMDir "$LOCALAPPDATA\\alef\\runtimes"
  Delete "$LOCALAPPDATA\\alef\\bin\\alef.cmd"
  RMDir "$LOCALAPPDATA\\alef\\bin"
  ReadRegStr $R2 HKCU "Environment" "Path"
  \${UnStrRep} $R3 "$R2" ";$LOCALAPPDATA\\alef\\bin" ""
  \${UnStrRep} $R3 "$R3" "$LOCALAPPDATA\\alef\\bin;" ""
  \${UnStrRep} $R3 "$R3" "$LOCALAPPDATA\\alef\\bin" ""
  WriteRegExpandStr HKCU "Environment" "Path" "$R3"
  SendMessage 0xFFFF 0x001A 0 "STR:Environment"
  DeleteRegKey HKCU "Software\\Classes\\Alef.Package\\shell\\open\\command"
  DeleteRegKey HKCU "Software\\Classes\\Alef.Package\\shell\\open"
  DeleteRegKey HKCU "Software\\Classes\\Alef.Package\\shell"
  DeleteRegKey HKCU "Software\\Classes\\Alef.Package"
  DeleteRegKey HKCU "Software\\Classes\\.alef"
un_done:
SectionEnd
`;
}

// Version-independent launcher: picks the highest installed version at run time.
const ALEF_CMD_SHIM = [
  '@echo off',
  'setlocal',
  'set "ALEF_RUNTIMES=%LOCALAPPDATA%\\alef\\runtimes"',
  'set "ALEF_V="',
  'for /f "usebackq delims=" %%V in (`powershell -NoProfile -Command "Get-ChildItem -LiteralPath $env:ALEF_RUNTIMES -Directory -ErrorAction SilentlyContinue | Where-Object { $_.Name -match \'^\\d+\\.\\d+\\.\\d+$\' } | Sort-Object { [version]$_.Name } | Select-Object -Last 1 -ExpandProperty Name"`) do set "ALEF_V=%%V"',
  'if not defined ALEF_V exit /b 2',
  '"%ALEF_RUNTIMES%\\%ALEF_V%\\alef.exe" %*',
].join('\r\n') + '\r\n';

function buildWin32({ version, runtime }) {
  const v = requireVersion(version);
  const bytes = requireRuntime(runtime);
  return [
    { path: `alef-runtime-${v}-setup.nsi`, data: Buffer.from(renderNsisScript(v), 'utf8'), mode: 0o644 },
    { path: 'build-installer.cmd', data: Buffer.from(`makensis /NOCD alef-runtime-${v}-setup.nsi\r\n`, 'utf8'), mode: 0o644 },
    { path: 'bin/alef.exe', data: bytes, mode: 0o755 },
    { path: 'bin/alef.cmd', data: Buffer.from(ALEF_CMD_SHIM, 'utf8'), mode: 0o755 },
  ];
}

const MIME_XML = [
  '<?xml version="1.0" encoding="UTF-8"?>',
  '<mime-info xmlns="http://www.freedesktop.org/standards/shared-mime-info">',
  '  <mime-type type="application/x-alef-package">',
  '    <comment>Alef application package</comment>',
  '    <glob pattern="*.alef"/>',
  '  </mime-type>',
  '</mime-info>',
].join('\n') + '\n';

// Constant values, but still run through the desktop helpers where interpolation
// would exist. quoteDesktopExec escapes % to %% so the field code goes outside it.
const DESKTOP_ENTRY = [
  '[Desktop Entry]',
  `Type=${escapeDesktopValue('Application')}`,
  `Name=${escapeDesktopValue('Alef Runtime')}`,
  `Exec=${quoteDesktopExec('alef')} run %f`,
  `Terminal=${escapeDesktopValue('false')}`,
  `Categories=${escapeDesktopValue('Utility;')}`,
  `MimeType=${escapeDesktopValue('application/x-alef-package;')}`,
  `StartupWMClass=${escapeDesktopValue('org.alef.runtime')}`,
].join('\n') + '\n';

function maintainerScript(template, version) {
  return template
    .replaceAll('<v>', version)
    .replaceAll('<prio>', String(alternativesPriority(version)));
}

const POSTINST = `#!/bin/sh
set -e
if command -v update-alternatives >/dev/null 2>&1; then
\tupdate-alternatives --install /usr/bin/alef alef /opt/alef-runtime/<v>/alef <prio>
fi
if command -v update-mime-database >/dev/null 2>&1; then
\tupdate-mime-database /usr/share/mime || true
fi
if command -v update-desktop-database >/dev/null 2>&1; then
\tupdate-desktop-database /usr/share/applications || true
fi
`;

